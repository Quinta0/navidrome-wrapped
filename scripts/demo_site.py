def demo_stats():
    """A plausible year of listening: skewed towards a few favourites, more at night, a summer peak."""
    r, listens, t0 = random.Random(7), [], datetime(YEAR, 1, 1).timestamp()
    for _ in range(4200):
        a = ARTISTS[min(int(r.expovariate(.35)), len(ARTISTS) - 1)]
        day = int(r.triangular(0, 330, 190))
        hour = r.choice([8, 9, 13, 18, 19, 20, 21, 21, 22, 22, 23, 0])
        listens.append({"ts": int(t0 + day * 86400 + hour * 3600 + r.randint(0, 3599)), "artist": a,
                        "title": TITLES[(ARTISTS.index(a) * 3 + int(r.expovariate(.6))) % len(TITLES)],
                        "album": f"{TITLES[ARTISTS.index(a) % len(TITLES)]} (Deluxe)" if r.random() < .5 else TITLES[ARTISTS.index(a) % len(TITLES)],
                        "secs": r.randint(150, 290)})
    listens.sort(key=lambda l: l["ts"])
    library = [{"id": f"{i}-{j}", "artist": a, "title": t, "duration": 220, "genre": GENRES[i % len(GENRES)],
                "playCount": r.randint(0, 60), "starred": "x" if r.random() < .2 else None,
                "year": 1968 + (i * 7 + j * 3) % 56, "suffix": "flac" if r.random() < .7 else "mp3", "bitRate": r.choice([320, 880, 1011, 1411])}
               for i, a in enumerate(ARTISTS) for j, t in enumerate(TITLES)]
    # one binge-and-forget song, a song on repeat one night, a long night session
    listens += [{"ts": int(t0 + (60 + d) * 86400 + 20 * 3600), "artist": "Ilse Varga", "title": "Fever Season", "album": "Fever Season", "secs": 230}
                for d in (0, 0, 1, 2, 2, 3, 5, 6)]
    night = t0 + 140 * 86400 + 22 * 3600
    listens += [{"ts": int(night + k * 240), "artist": a, "title": t, "album": "", "secs": 230}
                for k, (a, t) in enumerate([(ARTISTS[1], "Undertow")] * 11 + [(ARTISTS[k % len(ARTISTS)], TITLES[k % len(TITLES)]) for k in range(70)])]
    listens.sort(key=lambda l: l["ts"])
    last = {ARTISTS[0].lower(): t0 - 86400, ARTISTS[2].lower(): t0 - 86400, ARTISTS[5].lower(): t0 - 800 * 86400}
    prev = {a.lower(): [a, n] for a, n in zip(ARTISTS, [900, 120, 500, 60, 400, 10, 300, 20, 30, 200, 15, 5])}
    return compute(listens, library, last, prev, int(t0))


def card(seed, s, k):
    """The summary card of one design as inline SVG, with ids and keyframes made unique so several share a page."""
    g = Gen(seed)
    last = ("Top Genre", s["genres"][0][0]) if s["genres"] else ("New Artists", f"{s['n_new']:,}")
    svg = g.card_svg({"year": str(YEAR), "artists": [a for a, _ in s["artists"][:5]], "songs": [t for (t, _), _ in s["tracks"][:5]],
                      "minutes": s["minutes"], "label": last[0], "value": last[1], "name": s["artists"][0][0], "art": None})
    for i in ("cpat", "creg", "cart", "cclip", "cring", "cfade"):
        svg = re.sub(rf"\b{i}\b", f"{i}{k}", svg)
    pat = next(c for c in g.css if c.startswith("@keyframes cpat")).split(".in .card")[0].replace("cpat", f"cpat{k}")
    return svg, pat + f".c{k} .patmove{{animation:cpat{k} {8 + k % 5}s linear infinite}}", g



